"""Render SecBox dnsmasq configuration."""

from pathlib import Path

from secbox.modules.content_filter.models import ContentFilterConfig
from secbox.modules.dhcp.models import DhcpServerConfig


class DhcpRenderError(Exception):
    """Raised when dnsmasq configuration cannot be rendered."""


def render_dnsmasq_config(
    configs: list[DhcpServerConfig],
    output_path: Path,
    content_filter: ContentFilterConfig | None = None,
) -> Path:
    """Render combined SecBox DHCP and DNS configuration."""

    enabled_dhcp = [
        config
        for config in configs
        if config.enabled
    ]

    dns_enabled = (
        content_filter is not None
        and content_filter.enabled
        and content_filter.dns.enabled
    )

    if not enabled_dhcp and not dns_enabled:
        raise DhcpRenderError(
            "no enabled DHCP or DNS services configured"
        )

    lines: list[str] = [
        "# Generated by SecBox",
        "",
        "bind-interfaces",
    ]

    if not dns_enabled:
        lines.append("port=0")

    lines.append("")

    configured_interfaces: set[str] = set()

    for config in enabled_dhcp:
        configured_interfaces.add(config.interface)

        lines.extend(
            [
                f"interface={config.interface}",
                (
                    f"dhcp-range={config.range_start},"
                    f"{config.range_end},"
                    f"{config.network.netmask},"
                    f"{config.lease_time}"
                ),
                (
                    f"dhcp-option=interface:{config.interface},"
                    f"3,{config.gateway}"
                ),
            ]
        )

        dns_servers = config.dns_servers

        if (
            dns_enabled
            and content_filter is not None
            and config.interface
            == content_filter.dns.listen_interface
        ):
            dns_servers = [
                content_filter.dns.listen_address
            ]

        if dns_servers:
            dns_value = ",".join(
                str(server)
                for server in dns_servers
            )

            lines.append(
                (
                    f"dhcp-option=interface:{config.interface},"
                    f"6,{dns_value}"
                )
            )

        lines.append("")

    if dns_enabled and content_filter is not None:
        dns = content_filter.dns

        if dns.listen_interface not in configured_interfaces:
            lines.append(
                f"interface={dns.listen_interface}"
            )

        lines.extend(
            [
                f"listen-address={dns.listen_address}",
                "no-resolv",
            ]
        )

        for server in dns.upstream_servers:
            lines.append(
                f"server={server}"
            )

        lines.append("")

        for domain in content_filter.policy.blocked_domains:
            lines.extend(
                [
                    f"address=/{domain}/0.0.0.0",
                    f"address=/{domain}/::",
                ]
            )

        if content_filter.policy.blocked_domains:
            lines.append("")

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    output_path.write_text(
        "\n".join(lines),
        encoding="utf-8",
    )

    return output_path
