"""Render dnsmasq DHCP configuration."""

from pathlib import Path

from secbox.modules.dhcp.models import DhcpServerConfig


class DhcpRenderError(Exception):
    """Raised when DHCP configuration cannot be rendered."""


def render_dnsmasq_config(
    configs: list[DhcpServerConfig],
    output_path: Path,
) -> Path:
    """Render SecBox DHCP configuration for dnsmasq."""

    enabled_configs = [
        config
        for config in configs
        if config.enabled
    ]

    if not enabled_configs:
        raise DhcpRenderError("no enabled DHCP servers configured")

    lines: list[str] = [
        "# Generated by SecBox",
        "",
        "port=0",
        "bind-interfaces",
        "",
    ]

    for config in enabled_configs:
        lines.extend(
            [
                f"interface={config.interface}",
                (
                    f"dhcp-range={config.range_start},"
                    f"{config.range_end},"
                    f"{config.network.netmask},"
                    f"{config.lease_time}"
                ),
                f"dhcp-option=interface:{config.interface},3,{config.gateway}",
            ]
        )

        if config.dns_servers:
            dns_value = ",".join(
                str(server)
                for server in config.dns_servers
            )

            lines.append(
                f"dhcp-option=interface:{config.interface},6,{dns_value}"
            )

        lines.append("")

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    output_path.write_text(
        "\n".join(lines),
        encoding="utf-8",
    )

    return output_path
