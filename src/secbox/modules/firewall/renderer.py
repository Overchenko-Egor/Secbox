"""Render nftables configuration for SecBox."""

from ipaddress import IPv4Address
from pathlib import Path

from secbox.modules.firewall.models import FirewallConfig


class FirewallRenderError(Exception):
    """Raised when firewall configuration cannot be rendered."""


def render_nftables_config(
    config: FirewallConfig,
    output_path: Path,
    *,
    enforce_lan_dns: bool = False,
    block_dot: bool = False,
    block_doq: bool = False,
    enable_doh_set: bool = False,
    doh_resolver_addresses: list[IPv4Address] | None = None,
    vpn_interfaces: list[str] | None = None,
) -> Path:
    """Render nftables ruleset without applying it."""

    if not config.enabled:
        raise FirewallRenderError(
            "firewall is disabled"
        )

    vpn_interfaces = sorted(
        set(vpn_interfaces or [])
    )

    lines = [
        "# Generated by SecBox",
        "",
        "flush ruleset",
        "",
        "table inet secbox_filter {",
    ]

    if config.dynamic_blacklist_enabled:
        lines.extend(
            [
                "    set blacklist_v4 {",
                "        type ipv4_addr;",
                "        flags timeout;",
                f"        timeout {config.dynamic_blacklist_timeout};",
                "    }",
                "",
            ]
        )

    lines.extend(
        [
            "    set deception_sources_v4 {",
            "        type ipv4_addr;",
            "    }",
            "",
        ]
    )

    if enable_doh_set or doh_resolver_addresses:
        lines.extend(
            [
                "    set doh_resolvers_v4 {",
                "        type ipv4_addr;",
            ]
        )

        if doh_resolver_addresses:
            addresses = ", ".join(
                str(address)
                for address in sorted(
                    set(doh_resolver_addresses),
                    key=int,
                )
            )

            lines.append(
                f"        elements = {{ {addresses} }};"
            )

        lines.extend(
            [
                "    }",
                "",
            ]
        )

    deception_ingress = [
        config.wan_interface,
        config.lan_interface,
        *vpn_interfaces,
    ]

    deception_ingress = sorted(
        {
            interface
            for interface in deception_ingress
            if (
                interface
                and interface
                != config.management_interface
            )
        }
    )

    ingress_expression = ", ".join(
        f'"{interface}"'
        for interface in deception_ingress
    )

    lines.extend(
        [
            "    chain deception_prerouting {",
            "        type filter hook prerouting priority mangle;",
            "        policy accept;",
        ]
    )

    if ingress_expression:
        lines.extend(
            [
                "",
                (
                    f"        iifname {{ {ingress_expression} }} "
                    "ct mark 0x400 "
                    "meta mark set 0x400"
                ),
            ]
        )

    if ingress_expression:
        lines.extend(
            [
                (
                    f"        iifname {{ {ingress_expression} }} "
                    "ip saddr @deception_sources_v4 "
                    "ct state new "
                    "ct mark set 0x400 "
                    "meta mark set 0x400"
                ),
            ]
        )

    lines.extend(
        [
            "    }",
        ]
    )

    if ingress_expression:
        lines.extend(
            [
                "",
                "    chain deception_local_dnat {",
                "        type nat hook prerouting priority dstnat;",
                "        policy accept;",
                "",
                f"        iifname {{ {ingress_expression} }} ip saddr @deception_sources_v4 udp dport 53 dnat ip to 10.61.14.12",
                f"        iifname {{ {ingress_expression} }} ip saddr @deception_sources_v4 tcp dport 53 dnat ip to 10.61.14.12",
                (
                    f"        iifname {{ {ingress_expression} }} "
                    "ip saddr @deception_sources_v4 "
                    "fib daddr type local "
                    "dnat ip to 10.250.0.2"
                ),
                "    }",
            ]
        )

    lines.extend(
        [
            "",
            "    chain input {",
            "        type filter hook input priority 0;",
            f"        policy {config.input_policy};",
        ]
    )

    if config.dynamic_blacklist_enabled:
        lines.extend(
            [
                "",
                (
                    "        ip saddr @blacklist_v4 limit rate 5/second "
                    'log prefix "SECBOX_BLACKLIST_INPUT: "'
                ),
                "        ip saddr @blacklist_v4 counter drop",
            ]
        )

    lines.extend(
        [
            "",
            "        ct state established,related accept",
            "        ct state invalid drop",
            "",
            '        iifname "lo" accept',
        ]
    )

    if config.allow_icmp_input:
        lines.extend(
            [
                "",
                "        ip protocol icmp accept",
                "        ip6 nexthdr ipv6-icmp accept",
            ]
        )

    if config.management_tcp_ports:
        ports = ", ".join(
            str(port)
            for port in sorted(set(config.management_tcp_ports))
        )

        lines.extend(
            [
                "",
                (
                    f'        iifname "{config.management_interface}" '
                    f"tcp dport {{ {ports} }} "
                    "ct state new accept"
                ),
            ]
        )

    lines.extend(
        [
            "",
            (
                f'        iifname "{config.wan_interface}" '
                "udp sport 67 udp dport 68 accept"
            ),
        ]
    )

    if config.allow_dhcp_server:
        lines.extend(
            [
                "",
                (
                    f'        iifname "{config.lan_interface}" '
                    "udp sport 68 udp dport 67 accept"
                ),
            ]
        )

    if enforce_lan_dns:
        lines.extend(
            [
                "",
                (
                    f'        iifname "{config.lan_interface}" '
                    'udp dport 53 counter accept'
                ),
                (
                    f'        iifname "{config.lan_interface}" '
                    'tcp dport 53 counter accept'
                ),
            ]
        )

    if config.log_dropped_input and config.input_policy == "drop":
        lines.extend(
            [
                "",
                (
                    f"        limit rate {config.log_rate} "
                    f"burst {config.log_burst} packets "
                    'log prefix "SECBOX_INPUT_DROP: " '
                    "flags all counter"
                ),
            ]
        )

    lines.extend(
        [
            "    }",
            "",
            "    chain forward {",
            "        type filter hook forward priority 0;",
            f"        policy {config.forward_policy};",
            "",
            (
                '        meta mark 0x400 '
                'oifname "veth-dec-host" '
                'counter accept'
            ),
        ]
    )

    if config.dynamic_blacklist_enabled:
        lines.extend(
            [
                "",
                (
                    "        ip saddr @blacklist_v4 limit rate 5/second "
                    'log prefix "SECBOX_BLACKLIST_FORWARD: "'
                ),
                "        ip saddr @blacklist_v4 counter drop",
            ]
        )

    if enforce_lan_dns:
        lines.extend(
            [
                "",
                (
                    f'        iifname "{config.lan_interface}" '
                    'udp dport 53 counter drop'
                ),
                (
                    f'        iifname "{config.lan_interface}" '
                    'tcp dport 53 counter drop'
                ),
            ]
        )

    if block_doq:
        lines.extend(
            [
                "",
                (
                    f'        iifname "{config.lan_interface}" '
                    'udp dport 853 counter drop'
                ),
            ]
        )

    if block_dot:
        lines.extend(
            [
                "",
                (
                    f'        iifname "{config.lan_interface}" '
                    'tcp dport 853 counter drop'
                ),
            ]
        )

    if enable_doh_set or doh_resolver_addresses:
        lines.extend(
            [
                "",
                (
                    f'        iifname "{config.lan_interface}" '
                    'ip daddr @doh_resolvers_v4 '
                    'tcp dport 443 counter drop'
                ),
                (
                    f'        iifname "{config.lan_interface}" '
                    'ip daddr @doh_resolvers_v4 '
                    'udp dport 443 counter drop'
                ),
            ]
        )

    lines.extend(
        [
            "",
            "        ct state established,related accept",
            "        ct state invalid drop",
        ]
    )

    if config.allow_lan_to_wan:
        if vpn_interfaces:
            for vpn_interface in vpn_interfaces:
                lines.extend(
                    [
                        "",
                        (
                            f'        iifname "{config.lan_interface}" '
                            f'oifname "{vpn_interface}" '
                            "ct state new accept"
                        ),
                    ]
                )
        else:
            lines.extend(
                [
                    "",
                    (
                        f'        iifname "{config.lan_interface}" '
                        f'oifname "{config.wan_interface}" '
                        "ct state new accept"
                    ),
                ]
            )

    if config.log_dropped_forward and config.forward_policy == "drop":
        lines.extend(
            [
                "",
                (
                    f"        limit rate {config.log_rate} "
                    f"burst {config.log_burst} packets "
                    'log prefix "SECBOX_FORWARD_DROP: " '
                    "flags all counter"
                ),
            ]
        )

    lines.extend(
        [
            "    }",
            "",
            "    chain output {",
            "        type filter hook output priority 0;",
            f"        policy {config.output_policy};",
            "    }",
            "}",
        ]
    )

    if config.enable_nat:
        lines.extend(
            [
                "",
                "table ip secbox_nat {",
                "    chain postrouting {",
                "        type nat hook postrouting priority srcnat;",
                "        policy accept;",
                "",
                *(
                    [
                        (
                            f'        iifname "{config.lan_interface}" '
                            f'oifname "{vpn_interface}" '
                            "masquerade"
                        )
                        for vpn_interface in vpn_interfaces
                    ]
                    if vpn_interfaces
                    else [
                        (
                            f'        iifname "{config.lan_interface}" '
                            f'oifname "{config.wan_interface}" '
                            "masquerade"
                        )
                    ]
                ),
                "    }",
                "}",
            ]
        )

    lines.append("")

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    output_path.write_text(
        "\n".join(lines),
        encoding="utf-8",
    )

    return output_path
